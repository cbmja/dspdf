-- Sample schema for an isolated test database only. Production lengths and constraints require the source DDL.
CREATE TABLE STATUS (
    NUM INT IDENTITY(1,1) PRIMARY KEY,
    STATUS_CODE INT NOT NULL UNIQUE,
    STATUS_NAME NVARCHAR(100) NOT NULL,
    WAIT_TIME NVARCHAR(20) NULL,
    CHANGE_TYPE NVARCHAR(20) NOT NULL,
    CREATE_DATE DATETIME2(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE MASTER (
    MASTER_KEY NVARCHAR(128) PRIMARY KEY,
    TOTAL_SEND_CNT INT NOT NULL,
    STATUS INT NOT NULL,
    SEND_CNT INT NOT NULL,
    RECEIVED_TIME DATETIME2(3) NOT NULL,
    STATUS_TIME DATETIME2(3) NOT NULL,
    TYPE NVARCHAR(30) NOT NULL
);
CREATE TABLE DETAIL (
    PK NVARCHAR(160) PRIMARY KEY,
    TR_KEY NVARCHAR(128) NOT NULL,
    TOTAL_SEND_CNT INT NOT NULL,
    DLV_TYPE_CD NVARCHAR(20) NOT NULL,
    PRINT_TYPE_NM NVARCHAR(100) NOT NULL,
    PAGE_CNT INT NULL,
    RET_YN NVARCHAR(1) NULL,
    RECV_NUM INT NOT NULL,
    DM_LINK_KEY NVARCHAR(128) NOT NULL,
    CIFNO NVARCHAR(100) NULL,
    DLV_CD NVARCHAR(20) NULL,
    RECV_NM NVARCHAR(100) NOT NULL,
    RECV_POST_CD NVARCHAR(20) NOT NULL,
    RECV_ADDR NVARCHAR(500) NOT NULL,
    RECV_ADDR_DETAIL NVARCHAR(500) NULL,
    PDF_PATH NVARCHAR(1000) NOT NULL,
    SAVE_DATE DATETIME2(3) NOT NULL,
    MASTER NVARCHAR(128) NOT NULL,
    PDF_NM NVARCHAR(255) NOT NULL
);
CREATE INDEX IX_DETAIL_MASTER ON DETAIL(MASTER);
CREATE INDEX IX_DETAIL_TR_KEY ON DETAIL(TR_KEY);
CREATE TABLE ERROR (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ERROR_MESSAGE NVARCHAR(MAX) NOT NULL,
    CREATE_DATE DATETIME2(3) NOT NULL,
    MASTER_KEY NVARCHAR(128) NULL,
    ERROR_CODE NVARCHAR(100) NULL
);
